"""
Build the player avatar in Blender: body, garments, rig, FBX export.

Reads an anthropometric metrics JSON and writes an FBX ready for Unreal.
Bone names follow the UE5 Manny convention (see rig.py), so the exported
skeleton is recognised by retargeting, IK and engine animation tooling without
a mapping table.

The mesh is a reference body at the stature in the metrics file. AvatarAutoFit
refines it per player at runtime from measured height and arm span; regenerate
this file only when the anatomy itself changes.

Run inside Blender (Scripting workspace) or headless:
    blender --background --python build_avatar.py -- ^
        --metrics=C:\\Project\\Honeycomb\\Tools\\AvatarGen\\metrics.json ^
        --out=C:\\Project\\Honeycomb\\Content\\Avatars\\SK_HoneycombAvatar.fbx

Run verify_rig.py after any change here: it checks bone names, hierarchy,
landmark consistency and skin isolation without needing Blender.

Everything the generator produces is derived from the metrics file, so
regenerating for a different player is just a metrics change plus a re-run.
"""
import argparse
import json
import os
import sys

import bpy

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import geometry  # noqa: E402
import metrics as metrics_mod  # noqa: E402
import rig as rig_mod  # noqa: E402

CM_TO_M = 0.01

COLLECTION_NAME = "HoneycombAvatar"

# Garment set generated by default, mapped to material names.
DEFAULT_GARMENTS = ["tee", "trousers", "shoes"]

SKIN_MATERIAL = "M_Honeycomb_Skin"
GARMENT_MATERIALS = {
    "tee": "M_Honeycomb_Shirt",
    "longsleeve": "M_Honeycomb_Shirt",
    "tank": "M_Honeycomb_Shirt",
    "trousers": "M_Honeycomb_Trousers",
    "shorts": "M_Honeycomb_Shorts",
    "shoes": "M_Honeycomb_Shoes",
}


# --- scene helpers --------------------------------------------------------


def clear_generated():
    """Remove only what this script made, so the user's scene is preserved."""
    collection = bpy.data.collections.get(COLLECTION_NAME)
    if collection is None:
        return
    for obj in list(collection.objects):
        data = obj.data
        bpy.data.objects.remove(obj, do_unlink=True)
        if data is not None and data.users == 0:
            for lib in (bpy.data.meshes, bpy.data.armatures, bpy.data.materials):
                try:
                    lib.remove(data)
                    break
                except Exception:  # noqa: BLE001
                    continue
    bpy.data.collections.remove(collection)


def get_collection():
    collection = bpy.data.collections.get(COLLECTION_NAME)
    if collection is None:
        collection = bpy.data.collections.new(COLLECTION_NAME)
        bpy.context.scene.collection.children.link(collection)
    return collection


def make_material(name, colour, roughness=0.6, subsurface=0.0):
    mat = bpy.data.materials.get(name)
    if mat is None:
        mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    if bsdf is not None:
        bsdf.inputs["Base Color"].default_value = (colour[0], colour[1], colour[2], 1.0)
        bsdf.inputs["Roughness"].default_value = roughness
        # Blender 4.x renamed this socket; probe instead of assuming.
        for socket_name in ("Subsurface Weight", "Subsurface"):
            if socket_name in bsdf.inputs:
                bsdf.inputs[socket_name].default_value = subsurface
                break
    mat.diffuse_color = (colour[0], colour[1], colour[2], 1.0)
    return mat


def make_mesh_object(name, verts, faces, material, collection):
    mesh = bpy.data.meshes.new(name)
    scaled = [(v[0] * CM_TO_M, v[1] * CM_TO_M, v[2] * CM_TO_M) for v in verts]
    mesh.from_pydata(scaled, [], faces)
    mesh.validate()
    mesh.update()
    if material is not None:
        mesh.materials.append(material)
    obj = bpy.data.objects.new(name, mesh)
    collection.objects.link(obj)
    return obj


# --- rig ------------------------------------------------------------------


def make_armature(bones, collection, name="HoneycombAvatar_rig"):
    armature = bpy.data.armatures.new(name)
    obj = bpy.data.objects.new(name, armature)
    collection.objects.link(obj)

    view_layer = bpy.context.view_layer
    previous_active = view_layer.objects.active
    bpy.ops.object.mode_set(mode="OBJECT")
    view_layer.objects.active = obj
    obj.select_set(True)

    bpy.ops.object.mode_set(mode="EDIT")
    edit_bones = armature.edit_bones
    created = {}
    for bone_name, _parent, head, tail in bones:
        bone = edit_bones.new(bone_name)
        bone.head = (head[0] * CM_TO_M, head[1] * CM_TO_M, head[2] * CM_TO_M)
        bone.tail = (tail[0] * CM_TO_M, tail[1] * CM_TO_M, tail[2] * CM_TO_M)
        created[bone_name] = bone
    for bone_name, parent, _head, _tail in bones:
        if parent:
            created[bone_name].parent = created[parent]
            created[bone_name].use_connect = False
    bpy.ops.object.mode_set(mode="OBJECT")

    obj.select_set(False)
    if previous_active is not None:
        view_layer.objects.active = previous_active
    return obj


def apply_weights(mesh_obj, weights):
    """Attach the precomputed per-vertex weights as vertex groups."""
    names = []
    for entry in weights:
        for name, _w in entry:
            if name not in names:
                names.append(name)
    groups = {name: mesh_obj.vertex_groups.new(name=name) for name in names}

    for index, entry in enumerate(weights):
        for name, value in entry:
            if value <= 1e-4:
                continue
            groups[name].add([index], value, "REPLACE")
    return groups


def add_armature_modifier(mesh_obj, armature):
    modifier = mesh_obj.modifiers.new("Armature", "ARMATURE")
    modifier.object = armature
    return modifier


# --- build ----------------------------------------------------------------


def build(metrics, garments, segments, quality, collection):
    sections = metrics.sections()
    bones = rig_mod.build_bones(sections)

    skin_mat = make_material(SKIN_MATERIAL, (0.76, 0.55, 0.45), roughness=0.55, subsurface=0.12)
    garment_mats = {
        name: make_material(mat_name, (0.25, 0.28, 0.34), roughness=0.78)
        for name, mat_name in GARMENT_MATERIALS.items()
    }

    report = {"bones": len(bones), "garments": {}}

    body_verts, body_faces, parts, body_vparts = geometry.build_body(sections, segments, quality)
    body = make_mesh_object("SK_HoneycombBody", body_verts, body_faces, skin_mat, collection)

    weights = rig_mod.compute_weights(body_verts, bones, body_vparts)
    apply_weights(body, weights)
    add_armature_modifier(body, None)
    report["body_verts"] = len(body_verts)
    report["body_faces"] = len(body_faces)
    report["parts"] = sorted(parts.keys())

    for name in garments:
        gv, gf, gvparts = geometry.build_garment(name, sections, segments, quality)
        if not gf:
            report["garments"][name] = "skipped (no geometry)"
            continue
        mat = garment_mats.get(name)
        obj = make_mesh_object("SK_Honeycomb_" + name, gv, gf, mat, collection)
        gweights = rig_mod.compute_weights(gv, bones, gvparts)
        apply_weights(obj, gweights)
        add_armature_modifier(obj, None)
        report["garments"][name] = {"verts": len(gv), "faces": len(gf)}

    armature = make_armature(bones, collection)
    for obj in [body] + [
        o for o in collection.objects
        if o.type == "MESH" and o is not body
    ]:
        for modifier in obj.modifiers:
            if modifier.type == "ARMATURE":
                modifier.object = armature

    report["armature"] = armature.name
    report["bone_names"] = [b[0] for b in bones]
    return report


# --- export ---------------------------------------------------------------


def export_fbx(out_path, collection):
    """Export only the generated collection, rig and mesh, no camera/light."""
    directory = os.path.dirname(out_path)
    if directory and not os.path.isdir(directory):
        os.makedirs(directory)

    view_layer = bpy.context.view_layer
    for obj in view_layer.objects:
        obj.select_set(obj.name in collection.objects)

    bpy.ops.export_scene.fbx(
        filepath=out_path,
        use_selection=True,
        object_types={"ARMATURE", "MESH"},
        add_leaf_bones=False,
        primary_bone_axis="Y",
        secondary_bone_axis="X",
        use_armature_deform_only=True,
        bake_anim=False,
        mesh_smooth_type="FACE",
        path_mode="COPY",
        embed_textures=False,
    )
    return out_path


# --- entry ----------------------------------------------------------------


def parse_args(argv):
    parser = argparse.ArgumentParser()
    parser.add_argument("--metrics", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--segments", type=int, default=28)
    parser.add_argument("--quality", type=float, default=1.0)
    parser.add_argument("--garments", default=",".join(DEFAULT_GARMENTS))
    parser.add_argument("--report", default="")
    return parser.parse_args(argv)


def main(argv):
    args = parse_args(argv)
    collection = get_collection()
    clear_generated()
    collection = get_collection()

    player = metrics_mod.load(args.metrics)
    garments = [g.strip() for g in args.garments.split(",") if g.strip()]

    report = build(player, garments, args.segments, args.quality, collection)
    report["input"] = args.metrics
    report["output"] = args.out
    report["metrics"] = player.to_dict()
    report["fbx_size_kb"] = None

    export_fbx(args.out, collection)
    if os.path.exists(args.out):
        report["fbx_size_kb"] = round(os.path.getsize(args.out) / 1024, 1)

    if args.report:
        with open(args.report, "w", encoding="utf-8") as handle:
            json.dump(report, handle, indent=2, ensure_ascii=False)

    print("[build_avatar] " + json.dumps(
        {
            "body_verts": report["body_verts"],
            "body_faces": report["body_faces"],
            "bones": report["bones"],
            "garments": report["garments"],
            "fbx": report["output"],
            "fbx_size_kb": report["fbx_size_kb"],
        },
        ensure_ascii=False,
    ))
    return report


if __name__ == "__main__":
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    main(argv)