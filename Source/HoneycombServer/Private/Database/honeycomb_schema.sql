CREATE TABLE HC_PLAYERS (
    PLAYER_ID             NUMBER(19)      NOT NULL,
    NICKNAME              VARCHAR2(64)    NOT NULL,
    CHAKRA_LEVEL          NUMBER(10)      DEFAULT 1   NOT NULL,
    DIMENSION             NUMBER(10)      DEFAULT 3   NOT NULL,
    WORLD_INDEX           NUMBER(10)      DEFAULT 0   NOT NULL,
    KARMA                 NUMBER(10)      DEFAULT 0   NOT NULL,
    REINCARNATION_COUNT   NUMBER(10)      DEFAULT 0   NOT NULL,
    ENERGY                BINARY_DOUBLE   DEFAULT 100 NOT NULL,
    MAX_ENERGY            BINARY_DOUBLE   DEFAULT 100 NOT NULL,
    HEALTH                BINARY_DOUBLE   DEFAULT 100 NOT NULL,
    MAX_HEALTH            BINARY_DOUBLE   DEFAULT 100 NOT NULL,
    POS_X                 BINARY_DOUBLE   DEFAULT 0   NOT NULL,
    POS_Y                 BINARY_DOUBLE   DEFAULT 0   NOT NULL,
    POS_Z                 BINARY_DOUBLE   DEFAULT 0   NOT NULL,
    ROT_YAW               BINARY_DOUBLE   DEFAULT 0   NOT NULL,
    IS_DEAD               NUMBER(1)       DEFAULT 0   NOT NULL,
    MEDITATION_PROGRESS   BINARY_DOUBLE   DEFAULT 0   NOT NULL,
    COMPLETED_MEDITATIONS NUMBER(10)      DEFAULT 0   NOT NULL,
    UNLOCKED_CHAKRAS      VARCHAR2(4000)  DEFAULT '1',
    COMPLETED_WORLDS      VARCHAR2(4000)  DEFAULT '',
    CREATED_TS            NUMBER(19)      DEFAULT 0   NOT NULL,
    LAST_SAVE_TS          NUMBER(19)      DEFAULT 0   NOT NULL,
    CONSTRAINT HC_PLAYERS_PK PRIMARY KEY (PLAYER_ID)
);

CREATE INDEX HC_PLAYERS_LAST_SAVE_IDX ON HC_PLAYERS (LAST_SAVE_TS);
